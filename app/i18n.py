def site_language() -> str:
    """The language set on /options, English when unset, unknown or unreadable."""
    from app.models import Option
    try:
        row = Option.query.filter_by(meta_key=LANGUAGE_OPTION_KEY).first()
    except Exception:  # no database (yet): the UI still renders, in English
        from app import db
        db.session.rollback()
        return DEFAULT_LANGUAGE
    value = (row.meta_value or "").strip().lower() if row else ""
    return value if value in LANGUAGES else DEFAULT_LANGUAGE


def current_language() -> str:
    """
    The language of this request, read once from the option. Kept on the
    request rather than on g, whose app context can outlive a request (tests,
    CLI), so a change on /options shows on the very next page.
    """
    if not has_request_context():
        return DEFAULT_LANGUAGE
    if _ENVIRON_KEY not in request.environ:
        request.environ[_ENVIRON_KEY] = site_language()
    return request.environ[_ENVIRON_KEY]


def translate(text: str, lang: str | None = None) -> str:
    lang = lang if lang is not None else current_language()
    return SPANISH.get(text, text) if lang == "es" else text


def request_language() -> str:
    """
    /sales_by_location's language: the site's, unless ?lang= picks the other
    one to print a report in it. That choice is kept in the session while the
    site language stays what it was when it was made, so changing the setting
    on /options always wins.
    """
    site = site_language()
    lang = (request.args.get("lang") or "").strip().lower()
    if lang in LANGUAGES:
        if lang == site:
            session.pop("report_lang", None)
        else:
            session["report_lang"] = {"lang": lang, "site": site}
    chosen = session.get("report_lang")
    if isinstance(chosen, dict) and chosen.get("site") == site and chosen.get("lang") in LANGUAGES:
        lang = chosen["lang"]
    else:
        session.pop("report_lang", None)
        lang = site
    request.environ[_ENVIRON_KEY] = lang
    return lang


def init_app(app) -> None:
    @app.context_processor
    def _i18n():
        return {"_": translate, "lang": current_language(), "languages": LANGUAGES}
